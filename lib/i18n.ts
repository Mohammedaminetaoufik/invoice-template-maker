type WidenTranslation<T> = T extends string
  ? string
  : T extends readonly unknown[]
    ? { readonly [K in keyof T]: WidenTranslation<T[K]> }
    : T extends object
      ? { readonly [K in keyof T]: WidenTranslation<T[K]> }
      : T;

